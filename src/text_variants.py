class RecentHistory:
    """
    Помнит последние выданные фразы и не даёт выдать ту же самую подряд.

    Зачем: random.choice из одного списка регулярно выдаёт одну и ту же фразу
    два раза кряду — со стороны это выглядит как «кнопка не работает, текст не
    меняется». Здесь у каждого списка своя история: новая фраза выбирается
    только из тех, что не выдавались последними.

    История хранится в памяти процесса и на диск не пишется: после перезапуска
    повтор фразы безобиден, а лишний файл состояния — лишняя точка отказа.
    """

    def __init__(self, depth: int = 3) -> None:
        self._depth = max(1, int(depth))
        self._history: Dict[str, List[str]] = {}

    def pick(self, key: str, variants: Sequence[str], bucket: Optional[str] = None) -> str:
        """
        Возвращает вариант, которого не было среди последних выданных.

        Args:
            key:      имя списка («statuses», «cta»…) — история у каждого своя.
                      Ключ принято давать с префиксом версии («giga_» /
                      «tpl_»), когда одна и та же фраза встречается в обеих
                      программах: иначе они «съедали» бы варианты друг у друга.
            variants: список фраз.
            bucket:   необязательное имя истории. Нужно там, где варианты
                      собираются НА ЛЕТУ (например, стили маршрута с уже
                      подставленными городами): сравнивать сами строки
                      бессмысленно — они каждый раз разные, а не повторяться
                      должен СТИЛЬ. Если bucket задан, он и есть ключ истории.

        Returns:
            Выбранную фразу. Пустой список — пустую строку (не исключение:
            вызывающий код подставляет шаблон и не должен падать).
        """
        pool = [v for v in variants if v]
        if not pool:
            return ""
        if len(pool) == 1:
            return pool[0]

        store_key = bucket or key
        recent = self._history.setdefault(store_key, [])
        candidates = [v for v in pool if v not in recent]
        if not candidates:
            # Все варианты уже были в недавних — начинаем круг заново.
            recent.clear()
            candidates = pool

        choice = random.choice(candidates)
        recent.append(choice)

        # Держим историю короче самого списка, иначе выбор «не из недавних»
        # станет невозможным и мы будем каждый раз чистить историю.
        limit = min(self._depth, max(1, len(pool) - 1))
        del recent[:-limit]
        return choice

    def remember(self, key: str, value: str) -> None:
        """Запоминает фразу, полученную не через pick (например, от ИИ)."""
        if not value:
            return
        recent = self._history.setdefault(key, [])
        recent.append(value)
        del recent[:-self._depth]

    def clear(self, keep_last: bool = False) -> None:
        """Сбрасывает историю; новый вариант может сохранить запрет повтора.

        Полный сброс разрешал снова выбрать только что показанную фразу.
        keep_last оставляет по одной фразе, освобождая остальные варианты.
        Старые вызовы clear() сохраняют прежнее поведение.
        """
        if keep_last:
            self._history = {key: values[-1:] for key, values in self._history.items()}
        else:
            self._history.clear()


