def assemble_text(
    region: str,
    cities,
    pay_key: str,
    status_line: str,
    cta_line: str,
    *,
    header: Optional[str] = None,
    route_block: Optional[str] = None,
    payment: str = "",
    legal_line: str = "",
    opener: str = "",
    status_key: str = "statuses",
    cta_key: str = "",
    layout: str = "default",
) -> str:
    """
    Собирает финальный текст КП из готовых блоков.

    Единая точка сборки нужна, чтобы версия с ИИ и шаблонная версия давали
    ОДИНАКОВУЮ структуру: заголовок → маршрут → статус → оплата (+документы) →
    призыв. Раньше каждая программа клеила строки своим f-string, и блоки
    разъезжались: в одной был «💰», в другой нет, в одной пустая строка между
    блоками, в другой нет.

    Что подставляется кодом, а не аргументами:
      * заголовок — build_lot_header(region, cities), если header не задан;
      * блок маршрута — build_route_block(cities), если route_block не задан;
      * строка оплаты — payment_line(pay_key) с эмодзи «💰», если payment
        не передан (версия с ИИ передаёт строку, уже выбранную для промпта).

    Аргументы, которые могут быть пустыми:
      * opener      — открывающая фраза перед заголовком (шаблонная версия);
      * legal_line  — строка про договор и документы (шаблонная версия);
      * status_line — фраза про ожидание автовоза. Пусто — берём из STATUSES.
        Это единственное место с творчеством: если модель не дала внятной
        фразы, текст всё равно должен остаться про автовоз.

    Args:
        region:      регион лота;
        cities:      города лота (список или готовая строка);
        pay_key:     ключ типа оплаты;
        status_line: готовая фраза-статус (может быть пустой);
        cta_line:    готовый призыв к действию (может быть пустой — тогда
                     собирается из пула build_cta);
        header:      готовый заголовок (обычно не нужен: собирается сам);
        route_block: готовый блок маршрута (обычно не нужен: собирается сам);
        payment:     готовая строка оплаты БЕЗ эмодзи (для версии с ИИ);
        legal_line:  строка про договор (идёт в одну строку с оплатой);
        opener:      открывающая фраза перед заголовком;
        status_key:  ключ истории для шаблонного статуса;
        cta_key:     префикс ключа истории для призыва из пула.

    Returns:
        Готовый текст объявления. Блоки разделены пустой строкой; статус,
        оплата и документы идут слитно — это один смысловой абзац.
    """
    # Данные маршрута считаем ОДИН раз: заголовок и блок маршрута должны
    # говорить об одном и том же лоте.
    _pool, origin, points = _route_parts(cities)

    if header is None:
        header_line = _header_from_parts(region, points, origin)
    else:
        header_line = header

    if route_block is None:
        route = _route_from_parts(points, origin)
    else:
        route = route_block

    if not status_line:
        status_line = _history.pick(status_key, STATUSES)
    if not cta_line:
        if cta_key:
            pool = CTA_DISCUSS if pay_key == DISCUSS_PAYMENT_KEY else CTA_GENERIC
            cta_line = _history.pick(f"{cta_key}cta_{pay_key}", pool)
        else:
            cta_line = build_cta(pay_key)
    # Оплата — данные, а не креатив: строка берётся из настроек, слово в слово.
    # Если строка передана снаружи (её уже выбрал вызывающий код), берём её:
    # иначе выбор оплаты шёл бы второй раз и в одном тексте могли оказаться
    # две разные формулировки.
    payment_text = payment or payment_line(pay_key)
    payment_block = f"{PAYMENT_EMOJI} {payment_text}"
    if legal_line:
        payment_block = f"{payment_block} {legal_line}"

    blocks: List[str] = []
    if opener:
        blocks.append(opener)
    if header_line:
        blocks.append(header_line)
    if route:
        blocks.append(route)

    # Меняется только размещение готовых блоков. Данные и стандартный формат
    # прежних вызовов остаются прежними; ИИ-версия может выбрать другой ритм.
    if layout == "status_first":
        blocks.insert(0, status_line)
        tail = "\n".join((payment_block, cta_line))
    elif layout == "separate":
        tail = "\n\n".join((status_line, payment_block, cta_line))
    elif layout == "payment_first":
        tail = "\n".join((payment_block, status_line, cta_line))
    else:
        tail = "\n".join(line for line in (status_line, payment_block, cta_line) if line)
    if tail:
        blocks.append(tail)

    return "\n\n".join(blocks)
