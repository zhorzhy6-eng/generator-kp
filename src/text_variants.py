def pick_opener(city_count: int, prefix: str = "") -> str:
    """
    Открывающая строка для шаблонного текста: один город или сборный маршрут.

    Args:
        city_count: сколько городов в лоте;
        prefix:     префикс ключа истории. Нужен, чтобы истории двух версий
                    программы не пересекались («giga_» / «tpl_»).
    """
    if city_count <= 1:
        return _history.pick(f"{prefix}openers_one", OPENERS_ONE)
    return _history.pick(f"{prefix}openers_multi", OPENERS_MULTI)


