def _strip_list_marker(line: str) -> str:
    """Снимает маркеры списка, которыми города могли быть уже украшены."""
    line = line.lstrip("•▸■✦➜✅★>-–— \t").strip()
    for separator in (". ", ") "):
        head, found, tail = line.partition(separator)
        if found and head.strip().isdigit():
            return tail.strip()
    return line


def normalize_cities(cities) -> List[str]:
    """
    Приводит выбор городов к чистому списку пунктов маршрута.

    Принимает и список (как в версии с ИИ), и уже отформатированный текст
    (как в шаблонной версии): «• Ростов-на-Дону\\n1. Краснодар». Второй вариант
    разбирается обратно в список — иначе города нельзя было бы разложить по
    новым стилям маршрута.

    Два правила, без которых маршрут «рассыпается»:
      * креативный режим «Без города» — это РЕЖИМ, а не город: убираем;
      * «Владивосток → Москва» — это пара пунктов, а не один пункт: разбиваем
        по стрелке. Иначе цепочка получалась бы вида
        «Владивосток → Владивосток → Москва → Владивосток → Казань».

    Повторы убираются с сохранением порядка: «Владивосток» из двух пар — это
    один и тот же город погрузки.
    """
    if cities is None:
        return []

    if isinstance(cities, str):
        raw: List[str] = []
        for line in cities.splitlines():
            line = line.strip()
            if not line:
                continue
            raw.extend(part.strip() for part in _strip_list_marker(line).split(","))
    else:
        raw = [str(city).strip() for city in cities]

    result: List[str] = []
    for city in raw:
        # Город может быть как отдельным пунктом, так и направлением «X → Y»
        for point in (part.strip() for part in city.split("→")):
            if not point or point == CREATIVE_MODE:
                continue
            if point not in result:
                result.append(point)
    return result


def route_origin(cities: Sequence[str]) -> str:
    """
    Город погрузки.

    По умолчанию лот грузится в Москве. Владивосток — исключение: там машины
    отправляют ИЗ Владивостока, поэтому город погрузки — первый пункт маршрута
    (в этом регионе направления заданы парами «Владивосток → Москва»).

    Проверяем именно ПЕРВЫЙ пункт, а не весь список: после разбора направлений
    на пункты в списке есть и города выгрузки, из-за которых прежняя проверка
    «все города начинаются с „Владивосток“» перестала срабатывать.
    """
    pool = [c.strip() for c in cities if c and c.strip()]
    if pool and pool[0].startswith(VLADIVOSTOK):
        return VLADIVOSTOK
    return "Москва"


def destinations(cities: Sequence[str], origin: str = "") -> List[str]:
    """
    Пункты выгрузки БЕЗ города погрузки.

    Зачем: направления Владивостока заданы парами («Владивосток → Москва»),
    и после разбора на пункты Владивосток оказывается и городом погрузки, и
    первым пунктом списка. Без этой чистки в тексте получалось
    «Владивосток → Владивосток → Москва».

    Проверка идёт по ПЕРВОМУ пункту: город погрузки в цепочке всегда стоит
    первым, поэтому именно он и является лишним. Если список состоит из одного
    этого пункта (выбран только город погрузки) — отдаём его же: пустой маршрут
    хуже, чем повтор.
    """
    pool = [str(city).strip() for city in cities if str(city).strip()]
    if not pool:
        return []

    load_city = origin or route_origin(pool)
    if len(pool) > 1 and pool[0] == load_city:
        return pool[1:]
    return pool


def route_destination(cities: Sequence[str], origin: str = "", points: Optional[Sequence[str]] = None) -> str:
    """
    Город (или пара городов) выгрузки для ЗАГОЛОВКА.

    Для одного города — он сам. Для сборного маршрута — «первый → последний»:
    перечислять в заголовке все города нельзя, строка станет нечитаемой.
    """
    pool = list(points) if points is not None else destinations(cities, origin)
    if not pool:
        return ""
    if len(pool) == 1:
        return pool[0]
    return f"{pool[0]} → {pool[-1]}"


def _format_numbered(cities: Sequence[str], style: str = "numbered") -> str:
    """Города выгрузки отдельными строками: нумерация, маркеры, стрелки."""
    if style == "dots":
        return "\n".join(f"• {city}" for city in cities)
    if style == "dash":
        return "\n".join(f"— {city}" for city in cities)
    if style == "arrows":
        return "\n".join(f"➜ {city}" for city in cities)
    return "\n".join(f"{i + 1}. {city}" for i, city in enumerate(cities))


def _route_parts(cities) -> Tuple[List[str], str, List[str]]:
    """
    Разбирает выбор городов на части маршрута: пункты, погрузка, выгрузка.

    Вынесено отдельно, чтобы заголовок и блок маршрута считали это ОДИН раз и
    не могли разойтись: раньше каждый считал сам, и в заголовке с маршрутом
    легко было получить разные данные.

    Returns:
        (пункты маршрута, город погрузки, пункты выгрузки без города погрузки).
    """
    pool = normalize_cities(cities)
    if not pool:
        return [], "", []
    origin = route_origin(pool)
    return pool, origin, destinations(pool, origin)


def _header_from_parts(region: str, points: Sequence[str], origin: str) -> str:
    """
    Заголовок по уже разобранным частям маршрута.

    Заголовок описывает лот ЦЕЛИКОМ: город погрузки в него входит, а «{to}» —
    это пункт выгрузки или пара «первый → последний» для сборного маршрута.
    """
    if not points:
        variants = LOT_HEADERS_CREATIVE.get(region, [DEFAULT_LOT_HEADER])
        return _history.pick(f"header_creative_{region}", variants)

    destination = route_destination(points, origin, points)

    # «Один город» — это один ПУНКТ ВЫГРУЗКИ: у лота «Владивосток → Москва»
    # пункт один, хотя в маршруте две точки, и заголовок про сборный маршрут
    # здесь был бы неправдой.
    if len(points) > 1:
        template = _history.pick("header_multi", LOT_HEADERS_MULTI)
    else:
        template = _history.pick("header_one", LOT_HEADERS_ONE)
    return template.format(origin=origin, to=destination)


def build_lot_header(region: str, cities) -> str:
    """
    Заголовок объявления: {origin} → {to}, оформление — из пула шаблонов.

    Args:
        region: регион лота («Юга» / «Владивосток» / «Восток»);
        cities: города лота (список или готовая строка).

    Returns:
        Готовую первую строку объявления. Городов нет (креативный режим
        «Без города») — заголовок описывает направление по региону.
    """
    _pool, origin, points = _route_parts(cities)
    return _header_from_parts(region, points, origin)


def _route_from_parts(points: Sequence[str], origin: str) -> str:
    """
    Блок маршрута по уже разобранным частям: меняется только оформление.

    В шаблонах ROUTE_STYLES есть два вида:
      * со своим полем «{origin}» — «📍 Погрузка: {origin}\\n📍 Выгрузка: {list}».
        Сюда данные выгрузки идут БЕЗ города погрузки: он уже подставлен
        в {origin}, и раньше получалось «Москва → Москва → Ростов-на-Дону»;
      * без «{origin}» — «📍 {origin} → {chain}». Сюда город погрузки, наоборот,
        нужно включить в цепочку: иначе маршрут начинался бы с выгрузки.
    """
    if not points:
        return ""

    # Пункты выгрузки без повторов (город погрузки в них уже не входит).
    dropoffs: List[str] = []
    for city in points:
        if city and city != origin and city not in dropoffs:
            dropoffs.append(city)
    if not dropoffs:
        dropoffs = [origin]

    # Цепочка целиком — для шаблонов без отдельного поля «{origin}».
    with_origin = [origin] + [c for c in dropoffs if c != origin]

    style = _history.pick("route", ROUTE_STYLES, bucket="route")
    cities = dropoffs if "{origin}" in style else with_origin

    if "{numbered}" in style:
        numbered_style = _history.pick(
            "route_numbered", ROUTE_NUMBERED_STYLES, bucket="route_numbered"
        )
        return style.format(
            origin=origin,
            numbered=_format_numbered(cities, numbered_style),
        )

    return style.format(
        origin=origin,
        first=dropoffs[0],
        last=dropoffs[-1],
        chain=" → ".join(cities),
        list=" + ".join(cities),
        lines="\n".join(cities),
    )


def build_route_block(cities) -> str:
    """
    Блок маршрута: данные из настроек, оформление — из пула ROUTE_STYLES.

    Маршрут строит КОД, а не модель: города с вкладки известны точно, а ИИ
    может их перепутать, дописать лишние или потерять часть.

    Стиль выбирается без повторов (bucket="route"): строки собираются на лету,
    поэтому сравнивать их между собой бессмысленно — не повторяться должно
    ОФОРМЛЕНИЕ.

    Args:
        cities: города лота — список названий или уже отформатированная строка
                (шаблонная версия передаёт строку).

    Returns:
        Блок маршрута (1–2 строки) или пустую строку, если городов нет.
    """
    _pool, origin, points = _route_parts(cities)
    return _route_from_parts(points, origin)


